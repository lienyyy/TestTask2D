namespace TestTask
{
    /// <summary>
    /// Пять нарисованных направлений. Значение = номер ряда в спрайт-листе (сверху вниз).
    /// Левые варианты получаются отражением правых.
    /// </summary>
    public enum Facing
    {
        Front = 0,      // спереди (вниз)
        FrontSide = 1,  // три четверти вправо (вниз-вправо)
        Side = 2,       // профиль вправо
        BackSide = 3,   // три четверти со спины (вверх-вправо)
        Back = 4,       // со спины (вверх)
    }
}
